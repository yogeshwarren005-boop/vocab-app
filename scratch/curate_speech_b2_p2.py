def test_validation():
    banned_phrases = ["quality of being", "state of being", "condition of being", "in academic literature", "academic lexicon"]
    
    for word, data in CURATED_SPEECH_B2_P2.items():
        assert len(data['primary_definition']) >= 25, f"{word} prim def too short"
        assert len(data['secondary_definition']) >= 25, f"{word} sec def too short"
        assert data['primary_definition'] != data['secondary_definition'], f"{word} defs match"
        
        for p in banned_phrases:
            assert p not in data['primary_definition'].lower(), f"{word} prim def has banned phrase"
            assert p not in data['secondary_definition'].lower(), f"{word} sec def has banned phrase"
            
        assert len(data['quotes']) == 3, f"{word} quotes != 3"
        authors = set(q['author'] for q in data['quotes'])
        assert len(authors) == 3, f"{word} authors not distinct"
        
        for q in data['quotes']:
            assert len(q['author']) >= 3, f"{word} author length"
            assert len(q['work']) >= 2, f"{word} work length"
            assert f"**{word}**" in q['sentence'], f"{word} target not bolded properly"
            
    print("All tests passed!")

if __name__ == '__main__':
    test_validation()
